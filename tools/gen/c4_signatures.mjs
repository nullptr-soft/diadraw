// Generates src/io/src/plantuml/c4_signatures.inc from the vendored C4-PlantUML files
// (third_party/C4-PlantUML): the parameter names of every procedure and function, so calls
// with named arguments ($tags="...") map to positions.
//   node tools/gen/c4_signatures.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
const dir = join(root, 'third_party/C4-PlantUML');
const signatures = {};
for (const file of readdirSync(dir)
  .filter((f) => f.endsWith('.puml'))
  .sort()) {
  const text = readFileSync(join(dir, file), 'utf8');
  for (const m of text.matchAll(
    /^\s*!(?:unquoted\s+)?(?:procedure|function)\s+(\$?[\w]+)\s*\(([^)]*)\)/gm,
  )) {
    signatures[m[1]] = m[2]
      .split(',')
      .map((p) => p.trim().split('=')[0].trim())
      .filter(Boolean);
  }
}
const commit = readFileSync(join(dir, 'COMMIT'), 'utf8').trim();
const rows = Object.entries(signatures).map(
  ([name, params]) =>
    `    {${JSON.stringify(name)}, {${params.map((p) => JSON.stringify(p)).join(', ')}}}`,
);
writeFileSync(
  join(root, 'src/io/src/plantuml/c4_signatures.inc'),
  `// Generated by tools/gen/c4_signatures.mjs from C4-PlantUML ${commit} (MIT). Do not edit.\n${rows.join(',\n')}\n`,
);
console.log(`${rows.length} signatures`);
