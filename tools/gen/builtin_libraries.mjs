// Generates src/library/src/builtin_libraries.inc: the built-in libraries (assets/builtin/<name>,
// each a library source folder) built by the core and compiled in as JSON text. Only libraries
// whose licence lets them ship with DiaDraw are built in. Needs the WebAssembly build:
//   npm run build -w @diadraw/wasm && node tools/gen/builtin_libraries.mjs
import { readdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
const { loadDiaDraw } = await import(join(root, 'src/wasm/dist/index.js'));
const dd = await loadDiaDraw();

const sources = join(root, 'assets/builtin');
const bundles = [];
let failed = false;
for (const name of readdirSync(sources).sort()) {
  const dir = realpathSync(join(sources, name));
  const manifest = readFileSync(join(dir, 'diadraw-library.json'), 'utf8');
  const built = dd.buildLibrary(manifest, (path) => {
    let file;
    try {
      file = realpathSync(join(dir, path));
    } catch {
      return undefined;
    }
    const rel = relative(dir, file);
    if (rel.startsWith('..') || rel.startsWith(sep)) return undefined; // stay inside the library
    return readFileSync(file, 'utf8');
  });
  for (const i of built.issues) {
    console.error(`${name}: ${i.severity}: ${i.path ? `${i.path}: ` : ''}${i.message}`);
    if (i.severity === 'error') failed = true;
  }
  if (!built.text) continue;
  if (built.license.status !== 'allowed') {
    console.error(`${name}: not built in: ${built.license.reason}`);
    continue;
  }
  bundles.push(JSON.parse(built.text));
}
if (failed) process.exit(1);

const json = JSON.stringify(bundles);
// Raw string literals in pieces (an array, not one concatenated literal), well under every
// compiler's literal size limit.
const pieces = [];
for (let i = 0; i < json.length; i += 8000) pieces.push(`R"dd(${json.slice(i, i + 8000)})dd"`);
writeFileSync(
  join(root, 'src/library/src/builtin_libraries.inc'),
  `// Generated by tools/gen/builtin_libraries.mjs from assets/builtin/. Do not edit.\n${pieces.join(',\n')}\n`,
);
console.log(
  `${bundles.length} built-in libraries (${json.length} bytes): ${bundles.map((b) => `${b.name}@${b.version}`).join(', ')}`,
);
