// Generates src/base/src/unicode_tables.inc from the JavaScript engine's own Unicode data, so the C++
// core's `\p{L}`, `\p{N}` and case mapping agree with the TypeScript packages:
//   node tools/gen/unicode_tables.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ranges = (re) => {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const inside =
      cp < 0x110000 && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (inside && start < 0) start = cp;
    if (!inside && start >= 0) {
      out.push([start, cp - 1]);
      start = -1;
    }
  }
  return out;
};
// Simple (one code point to one code point) case mappings, as toLowerCase/toUpperCase do them.
const mapping = (f) => {
  const out = [];
  for (let cp = 0; cp < 0x110000; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const s = String.fromCodePoint(cp);
    const t = f(s);
    if (t === s) continue;
    const cps = [...t];
    if (cps.length === 1) out.push([cp, cps[0].codePointAt(0)]);
  }
  return out;
};
const hex = (n) => `0x${n.toString(16).toUpperCase()}`;
const table = (name, rows) =>
  `constexpr std::uint32_t ${name}[][2] = {\n${rows.map(([a, b]) => `    {${hex(a)}, ${hex(b)}}`).join(',\n')}};\n`;
const text = [
  `// Generated by tools/gen/unicode_tables.mjs (Unicode ${process.versions.unicode}). Do not edit.`,
  table('kLetterRanges', ranges(/\p{L}/u)),
  table('kNumberRanges', ranges(/\p{N}/u)),
  table(
    'kToLower',
    mapping((s) => s.toLowerCase()),
  ),
  table(
    'kToUpper',
    mapping((s) => s.toUpperCase()),
  ),
].join('\n');
writeFileSync(
  fileURLToPath(new URL('../../src/base/src/unicode_tables.inc', import.meta.url)),
  text,
);
console.log(`${text.length} bytes`);
