"""Generates src/io/nfkd_table.inc: for each code point whose NFKD form, minus the combining
marks U+0300–U+036F, differs from itself, that replacement in UTF-8. This reproduces
`text.normalize('NFKD').replace(/[̀-ͯ]/g, '')` from the TypeScript importers for every
code point where it matters for identifiers (see below)."""
import re, sys, unicodedata

out = []
for cp in range(0x80, 0x30000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    ch = chr(cp)
    d = unicodedata.normalize('NFKD', ch)
    d = ''.join(c for c in d if not (0x300 <= ord(c) <= 0x36F))
    # Only mappings that can change an identifier matter: everything that is not an ASCII letter,
    # digit or `_` becomes `_` anyway, so keep results holding such characters, or nothing.
    if d != ch and (d == '' or re.search(r'[A-Za-z0-9_]', d)):
        out.append((cp, d))
lines = ['// Generated by tools/gen/nfkd_table.py (Unicode %s). Do not edit.' % unicodedata.unidata_version]
for cp, d in out:
    lit = ''.join('\\x%02x' % b for b in d.encode('utf-8'))
    lines.append('{0x%X, "%s"},' % (cp, lit))
open(sys.argv[1], 'w').write('\n'.join(lines) + '\n')
print(len(out), 'entries, Unicode', unicodedata.unidata_version)
